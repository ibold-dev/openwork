#!/usr/bin/env bash
# Prints the Devnet deployment facts and writes the web app's local env file.
#
# This does not create anything on chain: the program and the settlement mint
# already exist (see docs/deployments.md). Run scripts/devnet-smoke.sh for a
# fresh end-to-end run that creates its own mint and agreement.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

CLUSTER="${OPENWORK_CLUSTER:-devnet}"
RPC_URL="${OPENWORK_RPC_URL:-https://api.devnet.solana.com}"
PROGRAM_ID="GT6deu8TWzjUzu5grXg4zZiAxPosK7tyoykaLtVeLjR"
MINT="ENmQKqTu9FaWJtmwk3nXiNT3GxX6F4k7rZe8t2bqUYT8"

if ! command -v solana >/dev/null 2>&1; then
  echo "error: the Solana CLI is not installed" >&2
  exit 1
fi

echo "==> cluster: $CLUSTER ($RPC_URL)"
solana balance -u "$RPC_URL" || true

echo "==> program account"
solana program show "$PROGRAM_ID" -u "$RPC_URL" | sed -n '1,8p'

echo "==> settlement mint"
solana account "$MINT" -u "$RPC_URL" --output json 2>/dev/null |
  grep -E '"owner"|"lamports"' || true

cat > apps/web/.env.local <<EOF
# Generated by scripts/devnet-setup.sh. Not committed.
NEXT_PUBLIC_SOLANA_CLUSTER=${CLUSTER}
NEXT_PUBLIC_SOLANA_RPC_URL=${RPC_URL}
NEXT_PUBLIC_DEFAULT_MINT=${MINT}
NEXT_PUBLIC_DEFAULT_MINT_SYMBOL=tUSDC
OPENWORK_API_URL=http://127.0.0.1:8080
EOF

echo "==> wrote apps/web/.env.local"
echo
echo "The settlement mint is a test SPL token with no market value."
